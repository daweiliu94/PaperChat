import { build } from 'esbuild';
import { mkdir, copyFile, cp, readFile, writeFile, rm } from 'node:fs/promises';
const out = new URL('../dist/', import.meta.url);
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await build({ entryPoints: ['extension/src/background.ts', 'extension/src/content.ts', 'extension/src/reader.ts'], outdir: 'dist', bundle: true, format: 'iife', target: ['safari17'], minify: false, sourcemap: false, logLevel: 'warning' });
for (const file of ['manifest.json', 'reader.html']) await copyFile(`extension/${file}`, new URL(file, out));
for (const folder of ['cmaps', 'standard_fonts', 'wasm']) await cp(`node_modules/pdfjs-dist/${folder}`, new URL(folder, out), { recursive: true });
await copyFile('node_modules/pdfjs-dist/build/pdf.worker.mjs', new URL('pdf.worker.mjs', out));
await copyFile('node_modules/pdfjs-dist/web/pdf_viewer.css', new URL('pdf_viewer.css', out));
await copyFile('node_modules/pdfjs-dist/LICENSE', new URL('PDFJS-LICENSE.txt', out));
await copyFile('LICENSE', new URL('PaperChat-LICENSE.txt', out));
await copyFile('NOTICE.md', new URL('NOTICE.md', out));
await copyFile('THIRD_PARTY_NOTICES.txt', new URL('THIRD_PARTY_NOTICES.txt', out));
await copyFile('node_modules/dompurify/LICENSE', new URL('DOMPurify-LICENSE.txt', out));
await copyFile('node_modules/marked/LICENSE', new URL('marked-LICENSE.txt', out));
await cp('extension/icons', new URL('icons/', out), { recursive: true });
await writeFile(new URL('build-info.json', out), JSON.stringify({ version: JSON.parse(await readFile('package.json')).version }));
console.log('Built Safari web resources.');
